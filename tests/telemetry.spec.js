import {test,expect} from '@playwright/test'

test('five-minute feed synchronizes playback, live readings, alert and captured history',async({page},info)=>{
  const errors=[];page.on('pageerror',e=>errors.push(e.message))
  await page.clock.install()
  await page.goto('/dashboard.html')
  const panel=page.getByRole('region',{name:'Live demo telemetry',exact:true})
  await expect(panel.locator('[data-reading=heartRate]')).toHaveText('62')
  await page.getByRole('button',{name:'Restart demo',exact:true}).click()
  await page.clock.fastForward(120000)
  await expect(panel.getByRole('status')).toContainText('Demo alert:')
  await expect(panel.locator('[data-reading=heartRate]')).not.toHaveText('62')
  await expect(panel.locator('summary')).toContainText('(25/60)')
  const hr=await panel.locator('[data-reading=heartRate]').innerText()
  await page.getByRole('button',{name:'Help — open emergency mode'}).click()
  const frame=page.frameLocator('.emergency-frame')
  await expect(frame.locator('#demoHeart')).toHaveText(hr+' bpm')
  await frame.getByRole('button',{name:'Pause demo',exact:true}).click()
  const pausedAt=await page.evaluate(()=>window.HEALiumTelemetry.snapshot().seconds)
  await page.clock.fastForward(30000)
  expect(await page.evaluate(()=>window.HEALiumTelemetry.snapshot().seconds)).toBe(pausedAt)
  await expect(frame.locator('#demoTime')).toContainText('Paused')
  await expect(frame.locator('#demoHeart')).toHaveText(hr+' bpm')
  await page.getByRole('button',{name:'Back to dashboard'}).click()
  await expect(page.getByRole('button',{name:'Resume demo',exact:true})).toBeVisible()
  await page.getByRole('button',{name:'Notifications',exact:true}).click()
  await expect(page.getByRole('dialog',{name:'Alerts',exact:true})).toContainText('Demo alert:')
  await page.getByRole('button',{name:'Close alerts',exact:true}).click()
  await page.getByRole('button',{name:'Resume demo',exact:true}).click()
  await page.clock.fastForward(90000)
  await expect(panel.getByRole('status')).toContainText('Demo recovery')
  await page.clock.fastForward(90000)
  await expect(page.getByRole('button',{name:'Replay demo',exact:true})).toBeVisible()
  await expect(panel.locator('summary')).toContainText('(60/60)')
  await page.clock.fastForward(10000)
  await expect(page.getByRole('region',{name:'Simulated telemetry playback'})).toContainText('Complete · 5:00')
  const points = await page.locator('.heart-widget .sparkline polyline').getAttribute('points')
  expect(points.split(' ').every(point => { const y=Number(point.split(',')[1]); return y>=0 && y<=34 })).toBe(true)
  await page.screenshot({path:info.outputPath('live-demo.png'),fullPage:true})
  expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(page.viewportSize().width+1)
  await page.getByRole('button',{name:'Replay demo',exact:true}).click()
  await expect(panel.locator('summary')).toContainText('(1/60)')
  expect(errors).toEqual([])
})

test('paused demo persists through reload and missing data has a working retry',async({page})=>{
  await page.goto('/')
  await expect(page.locator('[data-reading=heartRate]')).not.toHaveText('—')
  await page.getByRole('button',{name:'Pause demo',exact:true}).click()
  const before=await page.evaluate(()=>window.HEALiumTelemetry.snapshot().seconds)
  await page.reload()
  await expect(page.getByRole('button',{name:'Resume demo',exact:true})).toBeVisible()
  expect(await page.evaluate(()=>window.HEALiumTelemetry.snapshot().seconds)).toBe(before)
  await page.route('**/data/demo-telemetry.json',route=>route.fulfill({status:503,body:'Unavailable'}))
  await page.reload()
  await expect(page.getByRole('button',{name:'Retry demo data',exact:true})).toBeVisible()
  await expect(page.locator('[data-reading=heartRate]')).toHaveText('—')
  await page.unroute('**/data/demo-telemetry.json')
  await page.getByRole('button',{name:'Retry demo data',exact:true}).click()
  await expect(page.locator('[data-reading=heartRate]')).not.toHaveText('—')
})

test('playback controls synchronize across two dashboard tabs',async({page,context})=>{
  await page.goto('/')
  await expect(page.getByRole('button',{name:'Pause demo',exact:true})).toBeEnabled()
  const other=await context.newPage();await other.goto('/')
  await expect(other.getByRole('button',{name:'Pause demo',exact:true})).toBeEnabled()
  await page.getByRole('button',{name:'Pause demo',exact:true}).click()
  await expect(other.getByRole('button',{name:'Resume demo',exact:true})).toBeVisible()
  const first=await page.evaluate(()=>window.HEALiumTelemetry.snapshot())
  const second=await other.evaluate(()=>window.HEALiumTelemetry.snapshot())
  expect(second.seconds).toBe(first.seconds);expect(second.sample).toEqual(first.sample)
  await other.getByRole('button',{name:'Restart demo',exact:true}).click()
  await expect(page.getByRole('button',{name:'Pause demo',exact:true})).toBeVisible()
  await expect(page.locator('[data-reading=heartRate]')).toHaveText('62')
  await other.close()
})
