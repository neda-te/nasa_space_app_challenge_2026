import { test, expect } from '@playwright/test'

test('emergency remains usable without WebGL and manual Escape closes only the tooltip first', async ({ page }) => {
  const errors=[];page.on('pageerror', e=>errors.push(e.message))
  await page.addInitScript(() => {
    const original=HTMLCanvasElement.prototype.getContext
    HTMLCanvasElement.prototype.getContext=function(type,...args){return /webgl/.test(type)?null:original.call(this,type,...args)}
  })
  await page.goto('/emergency/index.html')
  await page.locator('[data-action="type"][data-v="pain"]').click()
  await expect(page.locator('.fallback-notice')).toBeVisible()
  await page.locator('.fallback [data-action="rm"]').first().click()
  await expect(page.locator('#chips .chip')).toHaveCount(1)
  await page.locator('#restart').click()
  await page.locator('[data-action="type"][data-v="other"]').click()
  await page.locator('[data-action="item"][data-v="fatigue"]').click()
  await page.locator('[data-action="grp"][data-g="dur"][data-v="today"]').click()
  await page.locator('[data-action="grp"][data-g="sev"][data-v="mild"]').click()
  await page.locator('#next').click()
  const opener=page.locator('[data-action="guide"][data-v="blood"]').first()
  await opener.click()
  await expect(page.getByRole('button',{name:'Close',exact:true})).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(page.getByRole('button',{name:'About Instruction manual',exact:true})).toBeFocused()
  await expect(page.locator('#tip')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.locator('#tip')).not.toBeVisible()
  await expect(page.locator('#guide')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.locator('#guide')).not.toBeVisible()
  await expect(opener).toBeFocused()
  expect(errors).toEqual([])
})

test('breathing counts complete cycles once and changing pattern resets a paused session',async({page})=>{
  await page.clock.install()
  await page.goto('/')
  await page.getByRole('button',{name:/Breathing exercise/i}).filter({visible:true}).first().click()
  await page.locator('.sound-master').click()
  await page.locator('.sound-row').filter({hasText:'Breathing guidance'}).getByRole('button').click()
  await page.getByRole('button',{name:'Start session',exact:true}).click()
  for(let i=0;i<14;i++) await page.clock.runFor(1000)
  await expect(page.locator('.breathing-stage-bottom > div').last().locator('b')).toHaveText('1')
  await page.getByRole('button',{name:'Pause session',exact:true}).click()
  await page.getByRole('button',{name:'Focus',exact:true}).click()
  await expect(page.getByRole('button',{name:'Start session',exact:true})).toBeVisible()
  await page.getByRole('button',{name:'Start session',exact:true}).click()
  await expect(page.locator('.breath-pulse > div > span')).toHaveText('Inhale')
  await expect(page.locator('.breathing-stage-bottom > div').last().locator('b')).toHaveText('0')
})

test('check-in contains keyboard focus, closes with Escape and returns focus',async({page})=>{
  await page.goto('/')
  const opener=page.getByRole('button',{name:'Daily health assessment',exact:true})
  await opener.click()
  const close=page.getByRole('button',{name:'Close window',exact:true})
  await expect(close).toBeFocused()
  await page.keyboard.press('Shift+Tab')
  expect(await page.evaluate(()=>!!document.activeElement.closest('.wellness-modal'))).toBe(true)
  await page.keyboard.press('Escape')
  await expect(page.locator('.wellness-modal')).toHaveCount(0)
  await expect(opener).toBeFocused()
})

test('only one tooltip opens and hover dismissal does not steal keyboard focus',async({page})=>{
  await page.goto('/')
  const heart=page.getByRole('button',{name:'About Heart Rate',exact:true})
  const sleep=page.getByRole('button',{name:'About Sleep Cycle',exact:true})
  await heart.focus()
  await expect(page.getByRole('tooltip')).toHaveCount(1)
  await sleep.hover()
  await expect(page.getByRole('tooltip')).toHaveCount(1)
  await expect(page.getByRole('tooltip')).toContainText('Sleep Cycle')
  await page.keyboard.press('Escape')
  await expect(page.getByRole('tooltip')).toHaveCount(0)
  await expect(heart).toBeFocused()
})
