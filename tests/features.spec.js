import { test, expect } from '@playwright/test'

async function navigate(page, name) { await page.getByRole('navigation').getByRole('button', { name, exact: true }).click() }
async function noOverflow(page) { expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(page.viewportSize().width + 1) }
async function modelFrame(page) {
  await expect(page.locator('.shared-body-model')).toBeVisible()
  const frame = page.frameLocator('.shared-body-model')
  await expect(frame.locator('#gl')).toHaveAttribute('aria-label', /3D body model/)
  return frame
}
async function bodyFits(frame) {
  await expect.poll(() => frame.evaluate(() => {
    scene.updateMatrixWorld(true); camera.updateMatrixWorld(true)
    const box = new THREE.Box3().setFromObject(pivot), points = []
    for (const x of [box.min.x,box.max.x]) for (const y of [box.min.y,box.max.y]) for (const z of [box.min.z,box.max.z]) {
      points.push(new THREE.Vector3(x,y,z).project(camera).y)
    }
    return Math.max(...points.map(Math.abs))
  })).toBeLessThan(.96)
}

test('alerts, complete tooltips, mission text, and sample CO₂ chart work with keyboard and taps', async ({ page }, info) => {
  const errors = []; page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  const bell = page.getByRole('button', { name: 'Notifications', exact: true })
  await bell.focus(); await page.keyboard.press('Enter')
  const alerts = page.getByRole('dialog', { name: 'Alerts', exact: true })
  await expect(alerts.getByText('Solar storm soon: high radiation alert.', { exact: true })).toBeVisible()
  await expect(alerts.getByText('Next blood tests on Wednesday.', { exact: true })).toBeVisible()
  await expect(alerts.getByRole('button', { name: 'Close alerts' })).toBeFocused()
  await page.keyboard.press('Escape'); await expect(alerts).not.toBeVisible(); await expect(bell).toBeFocused()
  await bell.click(); await alerts.getByRole('button', { name: 'Close alerts' }).click()
  const mission = page.locator('.current-mission')
  await expect(mission).toHaveText('Asteria VII')
  await expect(mission.locator('button,select,svg')).toHaveCount(0)
  for (const name of ['About Heart Rate', 'About Reaction time', 'About Scheduled blood test']) {
    const trigger = page.getByRole('button', { name, exact: true })
    await trigger.scrollIntoViewIfNeeded(); await trigger.focus()
    const tip = page.getByRole('tooltip'); await expect(tip).toBeVisible()
    const box = await tip.boundingBox(), viewport = page.viewportSize()
    expect(box.x).toBeGreaterThanOrEqual(0); expect(box.y).toBeGreaterThanOrEqual(0)
    expect(box.x + box.width).toBeLessThanOrEqual(viewport.width + 1)
    expect(box.y + box.height).toBeLessThanOrEqual(viewport.height + 1)
    if (name === 'About Reaction time') await expect(tip).toContainText('do not establish a diagnosis')
    await page.keyboard.press('ArrowDown'); await expect(tip).toBeFocused()
    await page.keyboard.press('Escape'); await expect(tip).not.toBeVisible()
    await trigger.click(); await expect(page.getByRole('tooltip')).toBeVisible()
    await page.keyboard.press('Escape')
  }
  await navigate(page, 'Trends & Analysis')
  await expect(page.getByRole('heading', { name: 'CO₂ trend', exact: true })).toBeVisible()
  await expect(page.locator('.co2-chart-card')).toContainText('NO CO₂ HISTORY CONNECTED')
  await page.locator('.co2-point').last().focus()
  await expect(page.locator('.co2-readout')).toContainText('2.1 mmHg')
  await page.locator('.page-title .range-tabs').getByRole('button', { name: '30 Days', exact: true }).click()
  await page.locator('.co2-point').last().focus()
  await page.locator('.page-title .range-tabs').getByRole('button', { name: '24 Hours', exact: true }).click()
  await expect(page.locator('.co2-chart svg')).toContainText('Time (UTC)')
  await page.getByText('View sample values', { exact: true }).click()
  await expect(page.locator('.sample-values tbody tr')).toHaveCount(13)
  await noOverflow(page)
  await page.locator('.co2-chart-card').scrollIntoViewIfNeeded()
  await page.screenshot({ path: info.outputPath('co2-and-tooltips.png') })
  expect(errors).toEqual([])
})

test('saved settings persist and synchronize real female/male 3D models and dark mode across views', async ({ page }, info) => {
  // Several software WebGL contexts can start slowly on shared Windows runners.
  test.setTimeout(240000)
  const errors = []; page.on('pageerror', error => errors.push(error.message))
  await page.goto('/'); await navigate(page, 'Dashboard Settings')
  const model = await modelFrame(page)
  await expect(model.locator('#gl')).toHaveAttribute('aria-label', 'Female 3D body model')
  const frame = page.frames().find(frame => frame.url().includes('view=body'))
  const femaleWidth = await frame.evaluate(() => bodySize.x)
  await page.getByLabel('Height (cm)', { exact: true }).fill('183.5')
  await page.getByLabel('Weight (kg)', { exact: true }).fill('88.2')
  await page.getByRole('button', { name: 'Save profile', exact: true }).click()
  await expect(page.getByText('Settings saved on this device.', { exact: true })).toBeVisible()
  await page.getByLabel('Gender', { exact: true }).selectOption('male')
  await expect(model.locator('#gl')).toHaveAttribute('aria-label', 'Male 3D body model')
  await expect.poll(() => frame.evaluate(() => bodySize.x)).not.toBe(femaleWidth)
  await bodyFits(frame)
  await page.getByRole('switch', { name: 'Dark mode', exact: true }).check()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  await expect(model.locator('html')).toHaveAttribute('data-theme', 'dark')
  await noOverflow(page)
  const contrast = await page.locator('.custom-controls section').first().evaluate(section => {
    const rgb = color => color.match(/[\d.]+/g).slice(0,3).map(Number)
    const luminance = color => rgb(color).map(value => { const c=value/255; return c<=.04045 ? c/12.92 : ((c+.055)/1.055)**2.4 }).reduce((sum,value,i)=>sum+value*[.2126,.7152,.0722][i],0)
    const foreground=luminance(getComputedStyle(section.querySelector('h3')).color), background=luminance(getComputedStyle(section).backgroundColor)
    return (Math.max(foreground,background)+.05)/(Math.min(foreground,background)+.05)
  })
  expect(contrast).toBeGreaterThanOrEqual(4.5)
  await page.screenshot({ path: info.outputPath('settings-dark.png'), fullPage: true })
  await page.reload(); await navigate(page, 'Dashboard Settings')
  await expect(page.getByLabel('Height (cm)', { exact: true })).toHaveValue('183.5')
  await expect(page.getByLabel('Weight (kg)', { exact: true })).toHaveValue('88.2')
  await expect(page.getByLabel('Gender', { exact: true })).toHaveValue('male')
  await expect(page.getByRole('switch', { name: 'Dark mode', exact: true })).toBeChecked()
  await navigate(page, 'Emergency Data'); const dashboardModel = await modelFrame(page)
  await expect(dashboardModel.locator('#gl')).toHaveAttribute('aria-label', 'Male 3D body model')
  await page.getByRole('button', { name: 'Help — open emergency mode' }).click()
  const emergency = page.frameLocator('.emergency-frame')
  await expect(emergency.locator('html')).toHaveAttribute('data-theme', 'dark')
  await expect(emergency.locator('#profileSummary')).toContainText('183.5 cm · 88.2 kg')
  await emergency.locator('[data-action="type"][data-v="pain"]').click()
  await expect(emergency.locator('#gl')).toHaveAttribute('aria-label', 'Male 3D body model')
  const other = await page.context().newPage(); await other.goto('/'); await navigate(other, 'Dashboard Settings')
  await other.getByLabel('Gender', { exact: true }).selectOption('female')
  await other.getByRole('switch', { name: 'Dark mode', exact: true }).uncheck()
  await expect(emergency.locator('#gl')).toHaveAttribute('aria-label', 'Female 3D body model')
  await expect(dashboardModel.locator('#gl')).toHaveAttribute('aria-label', 'Female 3D body model')
  await bodyFits(page.frames().find(frame => frame.url().includes('view=body')))
  await expect(emergency.locator('html')).toHaveAttribute('data-theme', 'light')
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light')
  await other.close()
  const tip = emergency.locator('.info[data-tip="pos"]')
  await tip.focus(); await page.keyboard.press('Enter')
  await expect(emergency.locator('#tip')).toBeVisible()
  const bounds = await emergency.locator('#tip').boundingBox()
  expect(bounds.x).toBeGreaterThanOrEqual(0); expect(bounds.x+bounds.width).toBeLessThanOrEqual(page.viewportSize().width+1)
  await page.keyboard.press('Escape')
  expect(errors).toEqual([])
})

test('full-screen breathing retains visible emergency and back controls and pauses for emergencies', async ({ page }, info) => {
  test.setTimeout(120000)
  const errors = []; page.on('pageerror', error => errors.push(error.message))
  await page.goto('/'); await navigate(page, 'Trends & Analysis')
  await page.getByRole('button', { name: 'Notifications', exact: true }).click()
  const desktop = page.locator('.sidebar-checkin.breathing')
  if (await desktop.isVisible()) await desktop.focus(); else await page.locator('.mobile-breathing').focus()
  await page.keyboard.press('Enter')
  const breathing = page.getByRole('dialog', { name: 'Full-screen breathing exercise', exact: true })
  await expect(breathing).toBeVisible()
  await expect(page.getByRole('dialog', { name: 'Alerts', exact: true })).not.toBeVisible()
  const bounds = await breathing.boundingBox(), viewport = page.viewportSize()
  expect(bounds.x).toBe(0); expect(bounds.y).toBe(0); expect(bounds.width).toBe(viewport.width); expect(bounds.height).toBe(viewport.height)
  const emergency = breathing.getByRole('button', { name: 'Emergency — open emergency mode', exact: true })
  const back = breathing.getByRole('button', { name: 'Go back', exact: true })
  await breathing.locator('.sound-master').click()
  await breathing.locator('.sound-row').filter({ hasText: 'Breathing guidance' }).getByRole('button').click()
  await breathing.getByRole('button', { name: 'Start session', exact: true }).click()
  await expect(breathing.getByText('Session in progress', { exact: true })).toBeVisible()
  await breathing.locator('.breathing-scroll').evaluate(element => { element.scrollTop = element.scrollHeight })
  const contentWidth = await breathing.locator('.breathing-scroll').evaluate(element => ({ content: element.scrollWidth, visible: element.clientWidth }))
  expect(contentWidth.content).toBeLessThanOrEqual(contentWidth.visible+1)
  await expect(emergency).toBeInViewport(); await expect(back).toBeInViewport()
  await page.screenshot({ path: info.outputPath('breathing-controls.png') })
  await emergency.click()
  await expect(page.getByRole('dialog', { name: 'Emergency mode', exact: true })).toBeVisible()
  await expect(page.frameLocator('.emergency-frame').locator('#s1')).toBeVisible()
  await page.getByRole('button', { name: 'Back to breathing exercise' }).click()
  await expect(breathing.getByRole('button', { name: 'Resume session', exact: true })).toBeVisible()
  await expect(emergency).toBeInViewport(); await back.click()
  await expect(breathing).not.toBeVisible()
  await expect(page.getByRole('heading', { name: 'Trends & Analysis', exact: true })).toBeVisible()
  await expect(page.locator('.app-shell')).not.toHaveAttribute('inert')
  await noOverflow(page)
  expect(errors).toEqual([])
})
